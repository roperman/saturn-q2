#!/usr/bin/env python3
"""Bake a Quake 2 map for the Saturn renderer.

    tools/bake_map.py data/pak0.pak maps/demo1.bsp cd/DEMO1.MAP [--res=2] [--preview=dir]

Every face is cut into a grid of cells, T x T texels of texture space, aligned
to the texture's repeat, so a whole cell is one VDP1 distorted sprite of a
shared tile. A cell the face only partly covers is drawn:
  - from the tile, with a range of its rows (srca/height), if the face covers
    whole rows of it (cut off at the top or bottom)
  - from the transposed tile, likewise, if it covers whole columns
  - otherwise from a variant: the tile cropped to what the face covers, with
    the uncovered texels transparent
Textures are 4bpp with a colour table (16 RGB entries, 0 = transparent) per
tile, so VDP1 Gouraud shading still works on them. Lighting: Quake's
lightmap, sampled at the grid's vertices, turned into Gouraud offsets.

Everything is big-endian for the SH-2. The layout matches src/level.h.
"""
import math
import os
import struct
import sys
from collections import defaultdict

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from q2data import Pak, Bsp, Wal, palette, SURF_SKY, SURF_NODRAW, SURF_WARP, SURF_TRANS33, SURF_TRANS66, SURF_FLOWING

T = 32                  # cell size in texels of texture space
EPS = 1e-4

# face flags (src/level.h)
FF_SKY, FF_WARP, FF_TRANS33, FF_TRANS66, FF_FLOWING, FF_NODRAW, FF_BACK, FF_LOD = 1, 2, 4, 8, 16, 32, 64, 128
TEX_TRANSPOSED = 0x8000
CELL_FULL = 0x8000          # a cell's tex: a whole tile; then its colour table, not ty0/th
CELL_EXACT = 0x4000         # a cropped cell that's exactly its grid cell (the face's edge is the grid's)
LOD_MIN = 12                # the faces with coarse grids: this many cells or more
# movers (src/q2.h)
MV_NONE, MV_STATIC, MV_DOOR, MV_PLAT, MV_BUTTON = 0, 1, 2, 3, 4
MF_START_OPEN, MF_PROXIMITY, MF_SHOOT = 1, 2, 4
