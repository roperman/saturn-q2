class Blob:
    def __init__(self):
        self.buf = bytearray()
        self.sizes = {}

    def add(self, data):
        while len(self.buf) & 31:
            self.buf.append(0)
        ofs = len(self.buf)
        self.buf += data
        self.sizes[ofs] = len(data)
        return ofs

    def data(self):
        return bytes(self.buf)


